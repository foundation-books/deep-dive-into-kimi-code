"""Render every operation of either printed finite physical manifest."""

from __future__ import annotations

import argparse

from .finite_fixture import complete_trace


def tex(value: str) -> str:
    """Escape the small plain-text vocabulary used by the manifest."""
    return value.replace("_", r"\_").replace("&", r"\&")


def render(compressed: bool) -> str:
    """Produce a deterministic, complete operation table, without a write."""
    trace = complete_trace(compressed)
    arm = "Compressed" if compressed else "Exact"
    slug = "compressed" if compressed else "exact"
    rows = [
        "% Generated by memory_efficient_training.render_fixture; do not hand-edit.",
        r"\begingroup\small\setlength{\tabcolsep}{2pt}",
        r"\begin{longtable}{@{}p{.06\textwidth}>{\raggedright\arraybackslash}p{.40\textwidth}"
        r"p{.10\textwidth}p{.10\textwidth}p{.12\textwidth}"
        r">{\raggedright\arraybackslash}p{.14\textwidth}@{}}",
        rf"\caption{{{arm} arm: complete finite physical operation sweep.}}",
        rf"\label{{tab:{slug}-physical-sweep}}\\",
        r"\toprule",
        r"ID & Object / operation; prerequisite & $P0$ & $P1$ & $H0/H1$ & Resource; slack \\",
        r"\midrule\endfirsthead",
        rf"\multicolumn{{6}}{{l}}{{{arm} arm: continued}}\\",
        r"\toprule",
        r"ID & Object / operation; prerequisite & $P0$ & $P1$ & $H0/H1$ & Resource; slack \\",
        r"\midrule\endhead",
        r"\bottomrule\endfoot",
        r"0 & fixed reservations & $18$ & $18$ & $5/5$ & -- \\",
    ]
    previous: tuple[int, ...] = (18, 18, 5, 5)
    for event, totals in zip(trace.events, trace.totals, strict=True):
        deltas = tuple(b - a for a, b in zip(previous, totals, strict=True))
        action = tex(f"{event.object}: {event.action}")
        requirement = tex(event.prerequisite)
        if event.units < 0:
            description = (
                action + r"\newline after last use/ready " + tex(event.justification)
            )
        else:
            description = action + r"\newline needs " + requirement
        h0 = f"${deltas[0]:+d}/{totals[0]}$"
        h1 = f"${deltas[1]:+d}/{totals[1]}$"
        host = rf"${deltas[2]:+d},{deltas[3]:+d}$\newline${totals[2]}/{totals[3]}$"
        resource = tex(event.resource)
        if event.slack is not None:
            resource += rf"\newline $S={event.slack}$"
        rows.append(
            f"{event.number} & {description} & {h0} & {h1} & {host} & {resource} "
            + r"\\"
        )
        previous = totals
    rows += [r"\end{longtable}", r"\endgroup", ""]
    return "\n".join(rows)


def main() -> None:
    """Print one complete manifest selected by its arithmetic arm."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--arm", choices=("exact", "compressed"), required=True)
    args = parser.parse_args()
    print(render(args.arm == "compressed"), end="")


if __name__ == "__main__":
    main()
